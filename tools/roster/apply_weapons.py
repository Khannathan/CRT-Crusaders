"""Writes src/data/weapons.ts: each Sister's signature weapon from her sister-bible card.

Usage (from the repo root):
    python3 -I tools/roster/apply_weapons.py /mnt/project-files/sister-bible/roster-500

Every card's IMAGE PROMPT names it: "Weapon (<tier>): <Name>, <what it looks like>; held: ...".
The tier is Epic (R), Legendary (SR), Mythic (SSR) or Divine Arsenal (UR). A card
without a named weapon is left out and the game names hers from her relic.
Run it again whenever the cards' weapons change.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'src' / 'data' / 'weapons.ts'
TIERS = {'Epic': 'epic', 'Legendary': 'legendary', 'Mythic': 'mythic', 'Divine Arsenal': 'divine'}
HEAD = re.compile(r'^### ([A-Z]{2}-[A-Z0-9]+(?:-[A-Z0-9]+)?):')
LINE = re.compile(r'^IMAGE PROMPT.*?Weapon \(([^)]+)\): (.+?); held: ')

weapons = {}
missing = []
for card in sorted(Path(sys.argv[1]).glob('[A-Z][A-Z]-*.md')):
    sid = None
    for line in card.read_text(encoding='utf-8').splitlines():
        h = HEAD.match(line)
        if h:
            if sid and sid not in weapons:
                missing.append(sid)
            sid = h.group(1)
            continue
        m = LINE.match(line)
        if sid and m and sid not in weapons:
            tier = TIERS.get(m.group(1))
            if not tier:
                sys.exit(f'{sid}: unknown weapon tier {m.group(1)!r}')
            name, _, look = m.group(2).partition(', ')
            weapons[sid] = {'name': name.strip(), 'tier': tier, 'look': look.strip()}
    if sid and sid not in weapons:
        missing.append(sid)

out = [
    '// Generated by tools/roster/apply_weapons.py from sister-bible/roster-500. Do not edit by hand.',
    "import type { WeaponTier } from './weaponTiers';",
    '',
    '/** Each Sister\'s signature weapon from her card: name, tier and what it looks like. */',
    'export const WEAPONS: Record<string, { name: string; tier: WeaponTier; look: string }> = {',
]
for sid in sorted(weapons):
    w = weapons[sid]
    out.append(f'  {json.dumps(sid)}: {{ name: {json.dumps(w["name"], ensure_ascii=False)}, tier: {json.dumps(w["tier"])}, look: {json.dumps(w["look"], ensure_ascii=False)} }},')
out.append('};')
OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'{len(weapons)} weapons written to {OUT.relative_to(ROOT)}')
if missing:
    print('No named weapon on these cards (the game names hers from her relic):', ', '.join(missing))
